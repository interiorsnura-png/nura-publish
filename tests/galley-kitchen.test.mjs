import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import * as cheerio from 'cheerio';
import sharp from 'sharp';
const nativeRequire=createRequire(import.meta.url);
const root=new URL('../',import.meta.url);
function load(relative){
 const file=new URL(relative,root),mod={exports:{}};
 const compiled=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,esModuleInterop:true}}).outputText;
 const require=id=>id.startsWith('.')?load(new URL(id+(id.endsWith('ArticleJourney')?'.tsx':'.ts'),file).pathname.replace(root.pathname,'')):nativeRequire(id);
 new Function('module','exports','require',compiled)(mod,mod.exports,require);return mod.exports;
}
const entries=['migration/content-backup.json','lib/published-editorial.json','lib/published-pages.json','lib/published-projects.json'].flatMap(file=>JSON.parse(fs.readFileSync(new URL(file,root),'utf8')));
const path='/post/planning-a-galley-kitchen-in-london';
const article=entries.find(e=>e.path===path);
const parent=entries.find(e=>e.path==='/guides/bespoke-kitchens');
const walk=nodes=>nodes.flatMap(n=>[n,...walk(n.children||[])]);

test('Galley guide, blueprint, reciprocal links and reviewed consultation journey are complete',async()=>{
 assert.equal(entries.filter(e=>e.path===path).length,1);
 const c=article.content,nodes=walk(c.body_nodes);
 assert.equal(c.title,'Planning a Galley Kitchen in London: Layout, Storage and Everyday Use');
 assert.equal(c.category,'Planning');
 assert.equal(c.author_name,'Nura Interiors');
 assert.deepEqual(c.reviewer,{name:'Alex J',role:'Execution and installation lead',reviewed_date:'2026-10-11'});
 assert.equal(c.pending_reviewer,undefined);
 assert.equal(nodes.filter(n=>n.type==='callout').length,1);
 assert.equal(c.body_nodes.find(n=>n.type==='callout').children[0].children.length,5);
 const prose=nodes.map(n=>n.text||'').join(' ');
 assert.match(prose,/single.run/i);assert.match(prose,/two facing runs/i);
 assert.match(prose,/1200 mm/);assert.match(prose,/not a universal legal minimum/);
 assert.match(prose,/ventilation/i);assert.match(prose,/daylight/i);
 assert.doesNotMatch(prose,/\u2014|guaranteed|complimentary/i);
 const image=c.body_nodes.find(n=>n.type==='image');
 assert.equal(image.src,'/assets/editorial/galley-kitchen-blueprint-infographic.webp');
 assert.match(image.alt,/1200 mm/);
 const asset=new URL('public'+image.src,root);
 assert.ok(fs.existsSync(asset));
 const metadata=await sharp(fileURLToPath(asset)).metadata();
 assert.ok(metadata.width>=1000&&metadata.height>metadata.width);
 assert.ok(Math.abs(metadata.width/metadata.height-3/4)<0.01);
 assert.ok(nodes.some(n=>n.link==='/guides/bespoke-kitchens'));
 assert.ok(walk(parent.content.body_nodes).some(n=>n.link===path));
 assert.ok(nodes.some(n=>n.link==='/kitchens/westover-road'));
 assert.ok(nodes.filter(n=>n.link==='/consultation').length>=2);
 const journey=load('lib/article-journeys.ts').getArticleJourney(path,entries);
 assert.equal(journey.proof.path,'/kitchens/westover-road');
 assert.equal(journey.enquiry.href,'/consultation');
 const $=cheerio.load(renderToStaticMarkup(React.createElement(load('components/ArticleJourney.tsx').default,{path,entries})));
 assert.equal($('.article-journey li').last().find('a').attr('href'),'/consultation');
 const related=load('lib/related-articles.ts').getRelatedArticles(article,entries).map(e=>e.path);
 assert.ok(related.includes('/guides/bespoke-kitchens'));
 assert.match(fs.readFileSync(new URL('components/RichArticle.tsx',root),'utf8'),/galley-kitchen-blueprint-infographic\.webp/);
});
